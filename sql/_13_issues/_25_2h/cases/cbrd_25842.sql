CREATE TABLE CURRENT_TIME_TBL (col1 int) PARTITION BY HASH (CURRENT_TIME() + col1) PARTITIONS 10;

CREATE TABLE CURRENT_TIME_TBL (col1 int) PARTITION BY HASH (CURRENT_TIME + col1) PARTITIONS 10;

