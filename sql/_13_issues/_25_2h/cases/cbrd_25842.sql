CREATE TABLE CURRENT_DATETIME_TBL(col1 int) PARTITION BY HASH(CURRENT_DATETIME + col1) PARTITIONS 10;

CREATE TABLE CURRENT_DATETIME_TBL(col1 int) PARTITION BY HASH(CURRENT_DATETIME() + col1) PARTITIONS 10;

CREATE TABLE CURRENT_DATETIME_TBL(col1 int) PARTITION BY HASH(NOW() + col1) PARTITIONS 10;

