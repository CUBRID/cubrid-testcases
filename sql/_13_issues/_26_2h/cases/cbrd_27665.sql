/**
 *  This test case verifies CBRD-27665: SET @var = <value> stores the value when the value
 *  uses LAST_INSERT_ID() or ROW_COUNT().
 *
 *  Such a SET is marked cannot_prepare at parse time, so it runs through do_statement ()
 *  even with the plan cache enabled. do_statement () had no case for SET/DROP VARIABLE:
 *  the statement printed "Execute OK" but the variable was not set, and reading it failed
 *  with "Session variable ... not defined". The fix runs do_set_session_variables () there.
 *
 *  The cases with the plan cache turned off (max_plan_cache_entries=0) need a server
 *  parameter change and are covered by the shell case cbrd_27665.
 */

drop table if exists t_27665;
create table t_27665 (id int auto_increment primary key, v int);

-- Case 1: LAST_INSERT_ID() is the id generated by the previous INSERT; expected 1
insert into t_27665 (v) values (10);
set @lid = last_insert_id();
select @lid;

-- Case 2: ROW_COUNT() is the number of rows inserted by the previous INSERT; expected 2
insert into t_27665 (v) values (20), (30);
set @rc = row_count();
select @rc;

-- Case 3: ROW_COUNT() is the number of rows updated by the previous UPDATE; expected 2
update t_27665 set v = v + 1 where id >= 2;
set @rc_upd = row_count();
select @rc_upd;

-- Case 4: LAST_INSERT_ID() in an expression, with a constant in the same SET; expected 104, 7
insert into t_27665 (v) values (40);
set @lid_expr = last_insert_id() + 100, @k = 7;
select @lid_expr, @k;

drop variable @lid, @rc, @rc_upd, @lid_expr, @k;
drop table t_27665;
