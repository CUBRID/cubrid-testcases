/**
 * This test case verifies CBRD-27163: stream size assert for filtered index
 * and partitioning key (filtered index part, plus the function index path
 * the same fix touched).
 *
 * Bug: a filtered index predicate is compiled into a FUNC_PRED stream and
 * stored in the class catalog with db_make_char(). Once the stream exceeds
 * DB_MAX_CHAR_PRECISION (2048 bytes) the value silently becomes NULL, while
 * the predicate TEXT limit is 1G, so the DDL succeeds. The index then loses
 * its predicate: the catalog shows it without its filter, and the index is
 * silently treated as a plain index. The issue comments also show that
 * creating one such index damages the filter info of indexes created
 * before it on the same table.
 * Fix (CUBRID/cubrid PR 7858): the filtered index stream, the function
 * index stream and the partition expression stream are now stored as
 * VARCHAR, and a failed filter/function/prefix info load is an error.
 *
 * Coverage:
 * 1 - Four filtered indexes whose streams were reported (issue comment) to
 *     stay below the old limit (IN lists of 3, 10, 110, 115 values): all
 *     keep their filter text.
 * 2 - Adding a 117-value IN-list filtered index: the new index AND the four
 *     earlier ones keep their filter text. This is the issue comment sequence;
 *     the 115/117 boundary was seen on a ko_KR.utf8 database. On an en_US
 *     database the 117-value stream still fits, and the loss starts at Case 3.
 * 3 - The report repro: a 1000-value IN-list filtered index.
 * 4 - A VARCHAR-column filtered index with a 150-value string IN list.
 * 5 - A 1000-value filtered index on a table holding 3 rows inside the
 *     filter and 10 rows outside it: after UPDATE STATISTICS ... WITH
 *     FULLSCAN, SHOW INDEX reports 3 keys for it (same as the 3-value
 *     control index). An index that lost its predicate would hold all 13.
 *     (A UNIQUE filtered index would be the natural oracle, but the grammar
 *     rejects UNIQUE with a filter/function index.)
 * 6 - Function index (stream now stored as VARCHAR): created, listed in
 *     db_index_key, and queried with USING INDEX (regression guard; a
 *     function index stream cannot reach 2048 bytes today).
 *
 * todo: reading a catalog written by an older version (CHAR stream) is also
 * part of the fix; it needs an old-version database and is out of SQL scope.
 */

