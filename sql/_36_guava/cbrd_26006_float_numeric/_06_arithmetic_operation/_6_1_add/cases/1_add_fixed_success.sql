evaluate '1. ADD Fixed NUMERIC(38,0): boundary add, cancellation, sign-mix, and Float promotion when the sum exceeds 38 digits';

DROP TABLE IF EXISTS t_add_succ_38_0;
DROP TABLE IF EXISTS t_add_succ_38_m84;
DROP TABLE IF EXISTS t_add_succ_38_127;
DROP TABLE IF EXISTS t_add_null_succ;

CREATE TABLE t_add_succ_38_0 (
  id INT,
  a  NUMERIC(38,0),
  b  NUMERIC(38,0),
  -- expected is Float NUMERIC: a + b promotes to Float and may exceed 38 digits (spec item 8)
  expected NUMERIC
);

-- (MAX-1) + 1 = MAX
INSERT INTO t_add_succ_38_0 VALUES
  (1,
   99999999999999999999999999999999999998,
   1,
   99999999999999999999999999999999999999);

-- (-MAX+1) + (-1) = -MAX
INSERT INTO t_add_succ_38_0 VALUES
  (2,
   -99999999999999999999999999999999999998,
   -1,
   -99999999999999999999999999999999999999);

-- Cancellation: MAX + (-MAX) = 0
INSERT INTO t_add_succ_38_0 VALUES
  (3,
   99999999999999999999999999999999999999,
   -99999999999999999999999999999999999999,
   0);

-- MAX + MAX = 199999999999999999999999999999999999998 (39 digits, promotes to Float, no overflow)
INSERT INTO t_add_succ_38_0 VALUES
  (4,
   99999999999999999999999999999999999999,
   99999999999999999999999999999999999999,
   199999999999999999999999999999999999998);

-- MIN + MIN = -199999999999999999999999999999999999998 (39 digits, promotes to Float, no overflow)
INSERT INTO t_add_succ_38_0 VALUES
  (5,
   -99999999999999999999999999999999999999,
   -99999999999999999999999999999999999999,
   -199999999999999999999999999999999999998);

-- Promotion shows up as a type change: a_type is numeric (38, 0) (Fixed) while
-- result_type is bare numeric (Float), for every row including id 1-3 whose sum fits in 38 digits.
SELECT id, a, b, a + b AS actual, expected,
       TYPEOF(a) AS a_type, TYPEOF(a + b) AS result_type,
       CASE WHEN a + b = expected THEN 'PASS' ELSE 'FAIL' END AS result
FROM t_add_succ_38_0
ORDER BY id;

evaluate '1-rt. Round-trip: store the result into a Fixed(38,0) column with no loss (fitting rows id 1-3)';
-- Same shape as t_add_succ_38_0, but expected is Fixed NUMERIC(38,0) and is populated by
-- storing a + b into it (Float result -> Fixed(38,0) conversion). For a fitting result the
-- stored value equals the recomputed a + b, so PASS means the round-trip is lossless.
-- Rows 4-5 (39 digits) would overflow on insert, so only id 1-3 are stored here
DROP TABLE IF EXISTS t_add_rt_38_0;
CREATE TABLE t_add_rt_38_0 (
  id INT,
  a  NUMERIC(38,0),
  b  NUMERIC(38,0),
  expected NUMERIC(38,0)
);
INSERT INTO t_add_rt_38_0
SELECT id, a, b, a + b FROM t_add_succ_38_0 WHERE id <= 3;

SELECT id, a, b, a + b AS actual, expected,
       TYPEOF(a) AS a_type, TYPEOF(a + b) AS result_type,
       CASE WHEN a + b = expected THEN 'PASS' ELSE 'FAIL' END AS result
FROM t_add_rt_38_0
ORDER BY id;
DROP TABLE IF EXISTS t_add_rt_38_0;


