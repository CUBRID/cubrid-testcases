/* 2. CREATE Float NUMERIC (default NUMERIC) */

evaluate '1. CREATE Float NUMERIC: SHOW CREATE TABLE output';
DROP TABLE IF EXISTS t1;
CREATE TABLE t1 (col1 NUMERIC);
SHOW CREATE TABLE t1;
DROP TABLE IF EXISTS t1;

evaluate '2. Float and Fixed NUMERIC columns in one table';
DROP TABLE IF EXISTS t1;
CREATE TABLE t1 (a NUMERIC, b NUMERIC(38,5), c NUMERIC, d NUMERIC(1,-84));
SHOW CREATE TABLE t1;
DROP TABLE IF EXISTS t1;

evaluate '3. Float NUMERIC with DEFAULT and NOT NULL';
DROP TABLE IF EXISTS t1;
CREATE TABLE t1 (col1 NUMERIC DEFAULT 1.5, col2 NUMERIC NOT NULL);
SHOW CREATE TABLE t1;
-- omit col1 so its DEFAULT applies, col2 is provided
INSERT INTO t1 (col2) VALUES (99999999999999999999999999999999999999);
SELECT * FROM t1;
DROP TABLE IF EXISTS t1;

evaluate '4. Float NUMERIC DEFAULT holding a large-precision value';
DROP TABLE IF EXISTS t1;
-- 40-digit default is beyond Fixed NUMERIC(38) range but Float NUMERIC holds it
CREATE TABLE t1 (col1 NUMERIC DEFAULT 1234567890123456789012345678901234567890, col2 INT);
SHOW CREATE TABLE t1;
INSERT INTO t1 (col2) VALUES (1);
SELECT * FROM t1;
DROP TABLE IF EXISTS t1;
