-- ELT returns the N-th argument; verify it handles NUMERIC values near boundaries.

-- ===========================================================================
-- Section 1: Float NUMERIC and Fixed NUMERIC boundary values
-- ===========================================================================
evaluate '1. Float NUMERIC and Fixed NUMERIC boundary values';
DROP TABLE IF EXISTS t1;
DROP TABLE IF EXISTS t2;
DROP TABLE IF EXISTS t4;
DROP TABLE IF EXISTS t5;
DROP TABLE IF EXISTS t6;
DROP TABLE IF EXISTS t7;
DROP TABLE IF EXISTS t3;
CREATE TABLE t1 (col1 NUMERIC, col2 VARCHAR(20));
INSERT INTO t1 VALUES (1234567890.123456789, 'abc');
SELECT ELT(1, col1, col2) FROM t1;
DROP TABLE IF EXISTS t1;

DROP TABLE IF EXISTS t2;
CREATE TABLE t2 (col1 NUMERIC(38,-30), col2 VARCHAR(4));
INSERT INTO t2 VALUES (-12345678901234567891234567890123456789000000000000000000000000000000, 'abcd');
SELECT ELT(1, col1, col2) FROM t2;
DROP TABLE IF EXISTS t2;

DROP TABLE IF EXISTS t4;
CREATE TABLE t4 (col1 NUMERIC(5,-20), col2 VARCHAR(15));
INSERT INTO t4 VALUES ( 1234500000000000000000000, 'abcd');
INSERT INTO t4 VALUES (-1234500000000000000000000, 'abcd');
SELECT ELT(1, col1, col2) FROM t4;
DROP TABLE IF EXISTS t4;

DROP TABLE IF EXISTS t5;
CREATE TABLE t5 (col1 NUMERIC, col2 VARCHAR(15));
INSERT INTO t5 VALUES ( 0.000000000000000000000000000000000000000012345, 'abcd');
INSERT INTO t5 VALUES (-0.000000000000000000000000000000000000000012345, 'abcd');
SELECT ELT(1, col1, col2) FROM t5;
DROP TABLE IF EXISTS t5;

-- Mixed type: numeric + int
DROP TABLE IF EXISTS t6;
