-- 길이 경계 확인
SELECT id, LENGTH(vc), OCTET_LENGTH(vc) FROM t02 ORDER BY LENGTH(vc), id;
-- 각 타입 기준 정렬(정렬 레코드 미니튜플, 고정 alignby 2/4, BIGINT/DOUBLE memcpy)
SELECT id, s, bi, fl, db FROM t02 ORDER BY bi, id;
SELECT id, db, fl FROM t02 ORDER BY db DESC, id;
SELECT id, s FROM t02 ORDER BY s, id;
SELECT id, dt, tm, ts, dtt FROM t02 ORDER BY dtt, id;
SELECT id, en, ch FROM t02 ORDER BY en, ch, id;
SELECT id, nu FROM t02 ORDER BY nu, id;
SELECT id, bt, vb FROM t02 ORDER BY bt, vb, id;
SELECT id, mo FROM t02 ORDER BY mo, id;
-- 가변 키 정렬 뒤 4KB 가변 컬럼 동반(4B 헤더)
SELECT id, ch, SUBSTR(vc, 1, 3), LENGTH(vc) FROM t02 ORDER BY ch, id;
-- 그룹/DISTINCT: 고정+가변 혼합 키
SELECT en, ch, COUNT(*), SUM(bi), MAX(nu) FROM t02 GROUP BY en, ch ORDER BY en, ch;
SELECT DISTINCT s, ch, bt FROM t02 ORDER BY s, ch, bt;
-- UNION 으로 도메인 통일(qfile_unify_types 경로)
SELECT id, ch AS k FROM t02 UNION SELECT id, vc FROM t02 WHERE LENGTH(vc) < 10 ORDER BY 1, 2;
-- 서브쿼리 결과 리스트 재스캔
SELECT a.id, b.id FROM t02 a, (SELECT id, bi FROM t02 ORDER BY bi) b WHERE a.bi = b.bi ORDER BY 1, 2;
